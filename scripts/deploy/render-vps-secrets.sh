#!/usr/bin/env bash
# Write /root/uniz-secrets.env from environment (GitHub Actions SSH env injection).
set -euo pipefail

OUT="${1:-/root/uniz-secrets.env}"
umask 077

env_line() {
  local key="$1"
  local val="${2-}"
  printf '%s=%q\n' "$key" "$val"
}

{
  echo "# Generated by UniZ CI — $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  env_line JWT_SECURITY_KEY "${JWT_SECURITY_KEY:-}"
  env_line INTERNAL_SECRET "${INTERNAL_SECRET:-}"
  env_line INTERNAL_BOT_SECRET "${INTERNAL_BOT_SECRET:-}"
  env_line REDIS_URL "${REDIS_URL:-}"
  env_line AWS_REGION "${AWS_REGION:-}"
  env_line AWS_ACCESS_KEY_ID "${AWS_ACCESS_KEY_ID:-}"
  env_line AWS_SECRET_ACCESS_KEY "${AWS_SECRET_ACCESS_KEY:-}"
  env_line SES_FROM_EMAIL "${SES_FROM_EMAIL:-}"
  env_line EMAIL_USER "${EMAIL_USER:-}"
  env_line EMAIL_PASS "${EMAIL_PASS:-}"
  env_line CLOUDINARY_CLOUD_NAME "${CLOUDINARY_CLOUD_NAME:-}"
  env_line CLOUDINARY_UPLOAD_PRESET "${CLOUDINARY_UPLOAD_PRESET:-}"
  env_line VITE_CLOUDINARY_CLOUD_NAME "${VITE_CLOUDINARY_CLOUD_NAME:-}"
  env_line VITE_CLOUDINARY_UPLOAD_PRESET "${VITE_CLOUDINARY_UPLOAD_PRESET:-}"
  env_line VAPID_PUBLIC_KEY "${VAPID_PUBLIC_KEY:-}"
  env_line VAPID_PRIVATE_KEY "${VAPID_PRIVATE_KEY:-}"
  env_line POSTGRES_USER "${POSTGRES_USER:-}"
  env_line POSTGRES_PASSWORD "${POSTGRES_PASSWORD:-}"
  env_line AUTH_DATABASE_URL "${AUTH_DATABASE_URL:-}"
  env_line USER_DATABASE_URL "${USER_DATABASE_URL:-}"
  env_line ACADEMICS_DATABASE_URL "${ACADEMICS_DATABASE_URL:-}"
  env_line OUTPASS_DATABASE_URL "${OUTPASS_DATABASE_URL:-}"
  env_line FILES_DATABASE_URL "${FILES_DATABASE_URL:-}"
  env_line MAIL_DATABASE_URL "${MAIL_DATABASE_URL:-}"
  env_line NOTIFICATION_DATABASE_URL "${NOTIFICATION_DATABASE_URL:-}"
  env_line CRON_DATABASE_URL "${CRON_DATABASE_URL:-}"
  env_line VITE_API_URL "${VITE_API_URL:-}"
  env_line VITE_MAINTENANCE_MODE "${VITE_MAINTENANCE_MODE:-}"
  env_line VITE_SCRAPER_URL "${VITE_SCRAPER_URL:-}"
  env_line VITE_ANALYTICS_URL "${VITE_ANALYTICS_URL:-}"
  env_line VITE_ANALYTICS_API_KEY "${VITE_ANALYTICS_API_KEY:-}"
  env_line INSTITUTION_LOGO_URL "${INSTITUTION_LOGO_URL:-}"
  env_line VITE_TURNSTILE_SITE_KEY "${VITE_TURNSTILE_SITE_KEY:-}"
  env_line TURNSTILE_SECRET_KEY "${TURNSTILE_SECRET_KEY:-}"
  env_line DB_USER "${DB_USER:-}"
  env_line DB_PASS "${DB_PASS:-}"
  env_line DB_HOST "${DB_HOST:-}"
  env_line LANDING_ANALYTICS_DB_HOST "${LANDING_ANALYTICS_DB_HOST:-172.17.0.1}"
  env_line DB_PORT "${DB_PORT:-}"
  env_line DB_NAME "${DB_NAME:-}"
  env_line LANDING_POSTGRES_USER "${LANDING_POSTGRES_USER:-}"
  env_line LANDING_POSTGRES_PASSWORD "${LANDING_POSTGRES_PASSWORD:-}"
  env_line LANDING_POSTGRES_DB "${LANDING_POSTGRES_DB:-}"
  env_line LANDING_DATABASE_URL "${LANDING_DATABASE_URL:-}"
  env_line LANDING_JWT_SECURITY_KEY "${LANDING_JWT_SECURITY_KEY:-}"
  env_line LANDING_JWT_ALGORITHM "${LANDING_JWT_ALGORITHM:-}"
  env_line DUMMY_TOKEN "${DUMMY_TOKEN:-}"
  env_line CLOUDFLARE_API_TOKEN "${CLOUDFLARE_API_TOKEN:-}"
  env_line CLOUDFLARE_TUNNEL_TOKEN "${CLOUDFLARE_TUNNEL_TOKEN:-}"
  env_line GHCR_USERNAME "${GHCR_USERNAME:-}"
  env_line GHCR_PULL_TOKEN "${GHCR_PULL_TOKEN:-}"
} >"$OUT"

chmod 600 "$OUT"
echo "[Secrets] Wrote $OUT ($(wc -l <"$OUT") lines)"
