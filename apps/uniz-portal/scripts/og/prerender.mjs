/**
 * Build-time Open Graph shells.
 *
 * Portal and landing ship as a direct upload of dist/ (see
 * scripts/deploy/deploy-cloudflare-pages.sh). Link-preview crawlers do
 * not run JavaScript, and a Pages Function that lives outside dist is
 * not part of that upload. Writing one HTML file per public route, and
 * _redirects rules for authenticated or unknown paths, puts the tags on
 * the bytes those crawlers download.
 *
 * Static files and the redirect rules name the same HTML, so the preview
 * is the same whether the host serves the file or applies _redirects first.
 *
 * Vite copies public/_redirects into dist before this runs. 3xx rules
 * from that file are kept and listed first so they are not overwritten
 * by the generated 200 rewrites (Nexus → UniZ 301s live there).
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { applyMeta, MARK_START } from "./html.mjs";

export function parseRedirects(text) {
  const rules = [];
  for (const line of String(text || "").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const parts = trimmed.split(/\s+/);
    if (parts.length < 2) continue;
    const [from, to, statusRaw] = parts;
    const status = statusRaw ? Number(statusRaw) : 302;
    if (!from || !to || Number.isNaN(status)) continue;
    rules.push({ from, to, status });
  }
  return rules;
}

export function mergeRedirects(existing, generated) {
  const seen = new Set();
  const out = [];
  for (const rule of existing) {
    if (rule.status >= 300 && rule.status < 400 && !seen.has(rule.from)) {
      seen.add(rule.from);
      out.push({ from: rule.from, to: rule.to, status: rule.status });
    }
  }
  for (const rule of generated) {
    if (seen.has(rule.from)) continue;
    seen.add(rule.from);
    out.push({ from: rule.from, to: rule.to, status: rule.status || 200 });
  }
  return out;
}

export function formatRedirects(rules) {
  const lines = [
    "# Link-preview shells. Exact paths are listed before prefix rules.",
    "# 3xx rules from public/_redirects stay first so they win over 200 rewrites.",
    "# Generated by scripts/og/prerender.mjs during the production build.",
  ];
  for (const rule of rules) {
    lines.push(`${rule.from}    ${rule.to}    ${rule.status || 200}`);
  }
  return `${lines.join("\n")}\n`;
}

export async function prerender({ appDir, routes }) {
  const dist = path.join(appDir, "dist");
  const indexPath = path.join(dist, "index.html");
  const html = await readFile(indexPath, "utf8");
  if (!html.includes(MARK_START)) {
    throw new Error(`${indexPath} is missing <!-- og:meta --> markers`);
  }

  for (const routePath of routes.prerenderPaths()) {
    const next = applyMeta(html, routes.resolve(routePath));
    if (routePath === "/") {
      await writeFile(indexPath, next);
      continue;
    }
    const dir = path.join(dist, routePath);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, "index.html"), next);
  }

  for (const shell of routes.shells || []) {
    let next = applyMeta(html, routes.resolve(shell.asPath));
    if (shell.stripJsonLd) {
      next = next.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/g, "");
    }
    const file = path.join(dist, shell.file);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, next);
  }

  let existing = [];
  try {
    existing = parseRedirects(await readFile(path.join(dist, "_redirects"), "utf8"));
  } catch {
    existing = [];
  }
  const rules = mergeRedirects(existing, routes.redirectRules());
  await writeFile(path.join(dist, "_redirects"), formatRedirects(rules));
  return dist;
}
